#!/usr/bin/env node
'use strict';
// The read-only Google Sheets snapshot is reviewed and committed with the site.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const snapshot = JSON.parse(fs.readFileSync(path.join(root, 'site/languages/editorial-source.json'), 'utf8'));
const copy = {};
for (const sheet of snapshot.sheets) {
  sheet.rows.slice(1).forEach((row, index) => {
    const key = sheet.name + ':' + (index + 2);
    if (!row[1] || !row[2]) throw Error('Missing EN/RU copy: ' + key);
    copy[key] = { en: row[1].trim(), ru: row[2].trim() };
    // Metadata and summary labels have their own semantic elements.
    const split = {
      '1 project:3': ['Problem:', 'Проблема:'], '1 project:4': ['Solution:', 'Решение:'],
      '1 project:5': ['Role', 'Роль'], '1 project:6': ['Team', 'Команда'], '1 project:7': ['Timeline', 'Таймлайн'],
      '2 project:3': ['Problem:', 'Проблема:'], '2 project:4': ['Solution:', 'Решение:'],
      '2 project:5': ['Role', 'Роль'], '2 project:6': ['Team', 'Команда'],
      '2 project:7': ['Collaboration', 'Кросс-командное взаимодействие']
    }[key];
    if (split) {
      if (!copy[key].en.startsWith(split[0]) || !copy[key].ru.startsWith(split[1])) throw Error('Unexpected metadata label: ' + key);
      copy[key + ':label'] = { en: split[0], ru: split[1] };
      copy[key + ':body'] = { en: copy[key].en.slice(split[0].length).trim(), ru: copy[key].ru.slice(split[1].length).trim() };
    }
    if (['1 project:47', '1 project:51', '2 project:49'].includes(key)) {
      copy[key + ':delta'] = { en: copy[key].en.match(/[+\d.,]+%/)[0], ru: copy[key].ru.match(/[+\d.,]+%/)[0] };
      copy[key + ':target'] = { en: 'vs target', ru: 'к плану' };
    }
    if (key === '2 project:51') copy[key + ':value'] = { en: copy[key].en.replace(/\s*↑/g, ''), ru: copy[key].ru.replace(/\s*↑/g, '') };
  });
}
const output = '// Generated by scripts/prepare-editorial-copy.js from the reviewed Google Sheets snapshot.\nwindow.siteEditorialCopy = ' + JSON.stringify(copy, null, 2) + ';\n';
const target = path.join(root, 'site/languages/editorial-copy.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw Error('Editorial copy is stale; run npm run copy:prepare');
} else fs.writeFileSync(target, output);
console.log('Editorial copy: ' + Object.keys(copy).length + ' bilingual entries checked.');
