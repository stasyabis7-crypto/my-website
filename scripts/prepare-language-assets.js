#!/usr/bin/env node
/* Inventory image slots and activate only files that actually exist. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
function variantPaths(source, lang) {
  const ext = path.extname(source);
  const base = source.slice(0, -ext.length);
  return /\.(mp4|webm)$/i.test(ext) ? [`${base}-${lang}${ext}`]
    : [...new Set([`${base}-${lang}.webp`, `${base}-${lang}${ext}`])];
}
function inventory() {
  const sources = new Map();
  function add(source, owner) {
    if (!source || /^(?:[a-z]+:|\/\/|#)/i.test(source)) return;
    const absolute = '/' + path.posix.normalize(path.posix.join(path.posix.dirname('/' + owner), source)).replace(/^\//, '');
    const key = source.startsWith('/') ? source.split(/[?#]/)[0] : absolute.split(/[?#]/)[0];
    if (!/\.(webp|gif|jpe?g|svg|mp4|webm)$/.test(key)) return;
    // Banner footage and ornamental assets remain the approved shared component.
    if (key.includes('/hero-mood/') || key.includes('/page-hero/pictures/')) return;
    if (!sources.has(key)) sources.set(key, new Set());
    sources.get(key).add(owner);
  }
  function visit(dir) {
    for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
      if (entry.name.startsWith('.') || ['node_modules', 'dev', 'scripts', 'docs'].includes(entry.name)) continue;
      const file = path.posix.join(dir, entry.name);
      if (entry.isDirectory()) visit(file);
      else if (file.endsWith('.html')) {
        const html = fs.readFileSync(path.join(root, file), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
        for (const tag of html.matchAll(/<(?:img|video|source)\b[^>]*>/g)) {
          for (const attr of tag[0].matchAll(/\b(?:src|poster|data-src)="([^"]+)"/g)) add(attr[1], file);
          for (const attr of tag[0].matchAll(/\bsrcset="([^"]+)"/g)) for (const part of attr[1].split(',')) add(part.trim().split(/\s+/)[0], file);
        }
      }
    }
  }
  visit('');
  const context = { window: {} };
  for (const file of ['pages/home/data/projects.js', 'projects/articles/articles.js']) vm.runInNewContext(fs.readFileSync(path.join(root, file), 'utf8'), context);
  for (const project of context.window.portfolioProjects) {
    for (const data of [project, project.feed]) if (data) for (const key of ['image', 'video']) add(data[key], 'pages/home/data/projects.js');
  }
  for (const article of context.window.portfolioArticles) for (const key of ['image', 'video']) add(article[key], 'projects/articles/articles.js');
  return [...sources].sort(([a], [b]) => a.localeCompare(b)).map(([source, owners]) => {
    const planned = {}, active = {};
    for (const lang of ['ru', 'en']) {
      const candidates = variantPaths(source, lang);
      planned[lang] = candidates[0];
      active[lang] = candidates.find(candidate => fs.existsSync(path.join(root, candidate))) || source;
    }
    return { source, planned, active, pages: [...owners].sort() };
  });
}
function prepareLanguageAssets({ check = false } = {}) {
  const slots = inventory();
  const media = Object.fromEntries(slots.map(slot => [slot.source, slot.active]));
  const outputs = {
    'site/languages/media-slots.json': JSON.stringify(slots, null, 2) + '\n',
    'site/languages/media.js': '// Generated by scripts/prepare-language-assets.js; only existing files are activated.\nwindow.siteLanguageMedia = ' + JSON.stringify(media, null, 2) + ';\n'
  };
  for (const [file, content] of Object.entries(outputs)) {
    if (fs.existsSync(path.join(root, file)) && fs.readFileSync(path.join(root, file), 'utf8') === content) continue;
    if (check) throw new Error(`${file} is stale; run npm run images:prepare`);
    fs.writeFileSync(path.join(root, file), content);
  }
  console.log(`Language media: ${slots.length} RU/EN slots checked.`);
  return slots;
}
if (require.main === module) prepareLanguageAssets({ check: process.argv.includes('--check') });
module.exports = { prepareLanguageAssets, variantPaths };
